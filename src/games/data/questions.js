function sample(list, n, not){
    let pool = list.filter(x => x !== not), out = []

    while(out.length < n && pool.length) out.push(pool.splice(Math.floor(Math.random() * pool.length), 1)[0])

    return out
}

/** [prompt, right, ...three wrong answers drawn from the other pairs] for every pair */
function generate(pairs, ask){
    let rights = pairs.map(p => p[1])

    return pairs.map(p => [ask(p[0]), p[1], ...sample(rights, 3, p[1])])
}

